-- Phase 2 universe expansion. Prospective/current snapshot only; never historical backfill.
create table if not exists public.flow_universe_contract_v1(
  universe_contract text primary key,
  target_count integer not null check(target_count>0),
  prospective_start_date date not null,
  eligibility_definition text not null,
  ranking_definition text not null,
  current_tradeable_definition text not null,
  production_actionable_definition text not null,
  historical_membership_state text not null check(historical_membership_state='CURRENT_TOP900_NOT_HISTORICAL'),
  frozen_at timestamptz not null default statement_timestamp(),
  production_influence_enabled boolean not null default false check(production_influence_enabled=false)
);

create table if not exists public.flow_universe_baseline_member_v1(
  baseline_contract text not null,
  ticker text not null,
  source_state text not null,
  captured_at timestamptz not null default statement_timestamp(),
  production_influence_enabled boolean not null default false check(production_influence_enabled=false),
  primary key(baseline_contract,ticker)
);

create table if not exists public.flow_universe_snapshot_v1(
  universe_contract text not null,
  snapshot_date date not null,
  ticker text not null,
  issuer_name text,
  sector text,
  subsector text,
  research_universe_eligible boolean not null,
  current_tradeable boolean not null,
  production_actionable boolean not null,
  selected_top900 boolean not null,
  universe_rank integer,
  selection_score numeric,
  selection_reason text not null,
  exclusion_reason text,
  data_quality_state text not null check(data_quality_state in ('AVAILABLE','STALE','INVALID','INSUFFICIENT_HISTORY')),
  liquidity_state text not null check(liquidity_state in ('ACTIVE_60D','SPORADIC_60D','NO_RECENT_TRADES_60D')),
  observed_sessions_60d integer not null,
  valid_close_sessions_60d integer not null,
  traded_sessions_60d integer not null,
  adtv_60d numeric not null,
  median_frequency_60d numeric not null,
  traded_sessions_252d integer not null,
  adtv_252d numeric not null,
  latest_source_date date,
  latest_traded_date date,
  source_completeness_pct numeric not null,
  membership_state text not null default 'CURRENT_TOP900_NOT_HISTORICAL'
    check(membership_state='CURRENT_TOP900_NOT_HISTORICAL'),
  captured_at timestamptz not null default statement_timestamp(),
  production_influence_enabled boolean not null default false check(production_influence_enabled=false),
  primary key(universe_contract,snapshot_date,ticker),
  check(not selected_top900 or (research_universe_eligible and universe_rank between 1 and 900))
);

create table if not exists public.flow_universe_capture_manifest_v1(
  universe_contract text not null,
  snapshot_date date not null,
  official_eod_date date,
  raw_registry_count integer not null,
  identity_valid_count integer not null,
  research_eligible_count integer not null,
  selected_count integer not null,
  baseline_overlap_count integer not null,
  excluded_count integer not null,
  current_tradeable_count integer not null,
  production_actionable_count integer not null,
  research_only_selected_count integer not null,
  source_sessions_60d integer not null,
  source_sessions_252d integer not null,
  selection_digest text,
  capture_state text not null,
  runtime_ms numeric,
  captured_at timestamptz not null default statement_timestamp(),
  production_influence_enabled boolean not null default false check(production_influence_enabled=false),
  primary key(universe_contract,snapshot_date)
);

