create or replace function public.flow_capture_universe_snapshot_v1(
  p_snapshot_date date default ((clock_timestamp() at time zone 'Asia/Jakarta')::date)
)
returns jsonb
language plpgsql
security invoker
set search_path=''
set work_mem='64MB'
as $fn$
declare
  v_contract text := 'TOP_900_UNIVERSE_V1';
  v_started timestamptz := clock_timestamp();
  v_eod date;
  v_s60 integer := 0;
  v_s252 integer := 0;
  v_raw integer := 0;
  v_identity integer := 0;
  v_eligible integer := 0;
  v_selected integer := 0;
  v_overlap integer := 0;
  v_excluded integer := 0;
  v_tradeable integer := 0;
  v_actionable integer := 0;
  v_research_only integer := 0;
  v_digest text;
  v_state text;
begin
  if p_snapshot_date < date '2026-09-09' then
    raise exception 'TOP_900_UNIVERSE_V1 cannot backfill before prospective start 2026-09-09';
  end if;

  select max(s.trade_date) into v_eod
  from public.flow_official_stock_summary s
  where s.source_verified and s.trade_date<=p_snapshot_date;

  if v_eod is not null then
    select count(*)::int into v_s252 from (
      select distinct s.trade_date
      from public.flow_official_stock_summary s
      where s.source_verified and s.trade_date<=v_eod
      order by s.trade_date desc limit 252
    ) d;
    v_s60 := least(v_s252,60);
  end if;

  select count(*)::int into v_raw from public.flow_issuers where active;

  if v_eod is null or v_s60<20 then
    insert into public.flow_universe_capture_manifest_v1(
      universe_contract,snapshot_date,official_eod_date,raw_registry_count,identity_valid_count,
      research_eligible_count,selected_count,baseline_overlap_count,excluded_count,
      current_tradeable_count,production_actionable_count,research_only_selected_count,
      source_sessions_60d,source_sessions_252d,capture_state,runtime_ms,production_influence_enabled
    ) values(
      v_contract,p_snapshot_date,v_eod,v_raw,0,0,0,0,0,0,0,0,v_s60,v_s252,
      'SOURCE_NOT_READY',extract(epoch from(clock_timestamp()-v_started))*1000,false
    ) on conflict(universe_contract,snapshot_date) do update set
      official_eod_date=excluded.official_eod_date,raw_registry_count=excluded.raw_registry_count,
      source_sessions_60d=excluded.source_sessions_60d,source_sessions_252d=excluded.source_sessions_252d,
      capture_state='SOURCE_NOT_READY',runtime_ms=excluded.runtime_ms,captured_at=statement_timestamp();
    return jsonb_build_object('status','SOURCE_NOT_READY','snapshot_date',p_snapshot_date,
      'official_eod_date',v_eod,'source_sessions_60d',v_s60,'production_influence_enabled',false);
  end if;

  delete from public.flow_universe_snapshot_v1
  where universe_contract=v_contract and snapshot_date=p_snapshot_date;

  with cal252 as (
    select distinct s.trade_date
    from public.flow_official_stock_summary s
    where s.source_verified and s.trade_date<=v_eod
    order by s.trade_date desc limit 252
  ), cal60 as (
    select trade_date from cal252 order by trade_date desc limit 60
  ), features as (
    select i.ticker,i.issuer_name,i.sector,i.subsector,
      (i.ticker~'^[A-Z0-9]{4}$' and coalesce(trim(i.issuer_name),'')<>'') identity_valid,
      count(s.trade_date) filter(where s.trade_date in(select trade_date from cal60))::int observed60,
      count(s.trade_date) filter(where s.trade_date in(select trade_date from cal60) and s.close>0)::int close60,
      count(s.trade_date) filter(where s.trade_date in(select trade_date from cal60) and s.traded_value>0 and s.frequency>0)::int traded60,
      coalesce(avg(s.traded_value) filter(where s.trade_date in(select trade_date from cal60)),0)::numeric adtv60,
      coalesce(percentile_cont(0.5) within group(order by s.frequency)
        filter(where s.trade_date in(select trade_date from cal60)),0)::numeric medfreq60,
      count(s.trade_date) filter(where s.traded_value>0 and s.frequency>0)::int traded252,
      coalesce(avg(s.traded_value),0)::numeric adtv252,
      max(s.trade_date) latest_source_date,
      max(s.trade_date) filter(where s.traded_value>0 and s.frequency>0) latest_traded_date,
      (array_agg(s.close order by s.trade_date desc) filter(where s.close>0))[1] latest_close,
      100.0*count(s.trade_date) filter(where s.trade_date in(select trade_date from cal60) and s.source_verified)
        /greatest((select count(*) from cal60),1) source_pct
    from public.flow_issuers i
    left join public.flow_official_stock_summary s
      on s.ticker=i.ticker and s.trade_date in(select trade_date from cal252) and s.source_verified
    where i.active
    group by i.ticker,i.issuer_name,i.sector,i.subsector
  ), eligible_scored as (
    select f.*,
      (
        0.50*percent_rank() over(order by ln(1+greatest(f.adtv60,0)))+
        0.20*percent_rank() over(order by f.traded60)+
        0.10*least(f.close60/60.0,1)+
        0.10*least(f.source_pct/100.0,1)+
        0.10*percent_rank() over(order by f.traded252)
      )::numeric selection_score
    from features f
    where f.identity_valid and f.close60>=20
  ), ranked as (
    select e.*,row_number() over(
      order by e.selection_score desc,e.latest_traded_date desc nulls last,e.ticker
    )::int universe_rank
    from eligible_scored e
  ), final as (
    select f.*,r.selection_score,r.universe_rank,
      (f.identity_valid and f.close60>=20) research_eligible,
      (f.identity_valid and f.close60>=20 and f.traded60>=5 and f.latest_close>0) tradeable,
      (f.identity_valid and f.close60>=50 and f.traded60>=20 and f.source_pct>=90
        and f.latest_source_date=v_eod and f.latest_close>0) actionable,
      (r.universe_rank between 1 and 900) selected
    from features f left join ranked r using(ticker)
  )
  insert into public.flow_universe_snapshot_v1(
    universe_contract,snapshot_date,ticker,issuer_name,sector,subsector,
    research_universe_eligible,current_tradeable,production_actionable,selected_top900,
    universe_rank,selection_score,selection_reason,exclusion_reason,data_quality_state,liquidity_state,
    observed_sessions_60d,valid_close_sessions_60d,traded_sessions_60d,adtv_60d,median_frequency_60d,
    traded_sessions_252d,adtv_252d,latest_source_date,latest_traded_date,source_completeness_pct,
    membership_state,production_influence_enabled
  )
  select v_contract,p_snapshot_date,ticker,issuer_name,sector,subsector,
    research_eligible,selected and tradeable,selected and actionable,selected,
    universe_rank,round(selection_score,10),
    case when selected and tradeable then 'TOP900_TRADEABLE_COMPOSITE'
         when selected then 'TOP900_RESEARCH_ONLY_SURVIVORSHIP_PRESERVATION'
         else 'NOT_SELECTED_TOP900' end,
    case when not identity_valid then 'INVALID_ISSUER_IDENTITY'
         when close60<20 then 'UNUSABLE_PRICE_HISTORY'
         when not selected then 'RANK_BELOW_TOP900'
         else null end,
    case when not identity_valid then 'INVALID'
         when close60<20 then 'INSUFFICIENT_HISTORY'
         when latest_source_date<v_eod or source_pct<90 then 'STALE'
         else 'AVAILABLE' end,
    case when traded60>=40 then 'ACTIVE_60D'
         when traded60>=5 then 'SPORADIC_60D'
         else 'NO_RECENT_TRADES_60D' end,
    observed60,close60,traded60,adtv60,medfreq60,traded252,adtv252,
    latest_source_date,latest_traded_date,round(source_pct,4),'CURRENT_TOP900_NOT_HISTORICAL',false
  from final;

  select
    count(*) filter(where ticker~'^[A-Z0-9]{4}$' and coalesce(trim(issuer_name),'')<>'')::int,
    count(*) filter(where research_universe_eligible)::int,
    count(*) filter(where selected_top900)::int,
    count(*) filter(where selected_top900 and exists(
      select 1 from public.flow_universe_baseline_member_v1 b
      where b.baseline_contract='IDX_OPERATIONAL_UNIVERSE_700_BASELINE_20260909'
        and b.ticker=flow_universe_snapshot_v1.ticker
    ))::int,
    count(*) filter(where not selected_top900)::int,
    count(*) filter(where selected_top900 and current_tradeable)::int,
    count(*) filter(where selected_top900 and production_actionable)::int,
    count(*) filter(where selected_top900 and not current_tradeable)::int
  into v_identity,v_eligible,v_selected,v_overlap,v_excluded,v_tradeable,v_actionable,v_research_only
  from public.flow_universe_snapshot_v1
  where universe_contract=v_contract and snapshot_date=p_snapshot_date;

  select md5(string_agg(
    ticker||':'||universe_rank::text||':'||coalesce(round(selection_score,10)::text,'NULL')||':'||
    current_tradeable::text||':'||production_actionable::text,
    '|' order by universe_rank
  )) into v_digest
  from public.flow_universe_snapshot_v1
  where universe_contract=v_contract and snapshot_date=p_snapshot_date and selected_top900;

  v_state := case when v_selected=900 then 'CAPTURED' else 'INSUFFICIENT_RESEARCH_ELIGIBLE' end;

  insert into public.flow_universe_capture_manifest_v1(
    universe_contract,snapshot_date,official_eod_date,raw_registry_count,identity_valid_count,
    research_eligible_count,selected_count,baseline_overlap_count,excluded_count,
    current_tradeable_count,production_actionable_count,research_only_selected_count,
    source_sessions_60d,source_sessions_252d,selection_digest,capture_state,runtime_ms,
    production_influence_enabled
  ) values(
    v_contract,p_snapshot_date,v_eod,v_raw,v_identity,v_eligible,v_selected,v_overlap,v_excluded,
    v_tradeable,v_actionable,v_research_only,v_s60,v_s252,v_digest,v_state,
    extract(epoch from(clock_timestamp()-v_started))*1000,false
  ) on conflict(universe_contract,snapshot_date) do update set
    official_eod_date=excluded.official_eod_date,raw_registry_count=excluded.raw_registry_count,
    identity_valid_count=excluded.identity_valid_count,research_eligible_count=excluded.research_eligible_count,
    selected_count=excluded.selected_count,baseline_overlap_count=excluded.baseline_overlap_count,
    excluded_count=excluded.excluded_count,current_tradeable_count=excluded.current_tradeable_count,
    production_actionable_count=excluded.production_actionable_count,
    research_only_selected_count=excluded.research_only_selected_count,
    source_sessions_60d=excluded.source_sessions_60d,source_sessions_252d=excluded.source_sessions_252d,
    selection_digest=excluded.selection_digest,capture_state=excluded.capture_state,
    runtime_ms=excluded.runtime_ms,captured_at=statement_timestamp();

  return jsonb_build_object('status',v_state,'universe_contract',v_contract,'snapshot_date',p_snapshot_date,
    'official_eod_date',v_eod,'raw_registry_count',v_raw,'research_eligible_count',v_eligible,
    'selected_count',v_selected,'baseline_overlap_count',v_overlap,'excluded_count',v_excluded,
    'current_tradeable_count',v_tradeable,'production_actionable_count',v_actionable,
    'research_only_selected_count',v_research_only,'selection_digest',v_digest,
    'production_influence_enabled',false);
end
$fn$;

